/**
 * Casinos in REAL terrain (lane CB-5, architecture §9.4 / §9.5): default-preset worlds for two seeds, the nearest
 * casino located like {@code /locate} does, the player sent there, chunks generated by the game, then on the server:
 * (a) no floating foundation, (b) no terrain cut into the building, (c) every game reachable on foot from outside;
 * a front photo; and the cost of generating the 9×9 chunks around a casino against a casino-free control area
 * (≤ 3×, see {@link #COST_RATIO}). Before the v0.2 structures exist the same checks run on a village with its casino annex (village casino
 * chance forced to 1 for the test).
 */
public class CasinoTerrainClientGameTests implements FabricClientGameTest {
	private static final long[] SEEDS = {12345L, 42L};
	private static final int CHUNK_WAIT = 1200;
	/**
	 * Worldgen cost bar (INT-X, owner: worldgen only needs to be "roughly fine"). The control area is casino-free but not
	 * like-for-like: at seed 12345 the ice palace site also holds a snowy village (its record is casino/annex/snowy) and
	 * ice-spikes terrain. The old ~2× (and a 7.2× riviera outlier) was the timed area paying for the player's queued
	 * view-distance chunks (GENPERF); with {@link #drain} first, every site measures 0.8–1.25×. 3× + 250 ms still catches a
	 * pathological regression (a per-block loop, a chunk-load storm) without failing on village/biome noise or a busy
	 * machine.
	 */
	static final double COST_RATIO = 3.0;
	static final long COST_SLACK_MS = 250;

	private final List<String> failures = new ArrayList<>();

	@Override
	public void runTest(ClientGameTestContext context) {
		double chance = CasinoConfig.worldgen().villageCasino.chance;
		try {
			for (long seed : SEEDS) {
				runSeed(context, seed);
			}
		} finally {
			CasinoConfig.worldgen().villageCasino.chance = chance;
		}
		if (!failures.isEmpty()) {
			throw new AssertionError("casinos in real terrain:\n  " + String.join("\n  ", failures));
		}
	}

	private record Found(BlockPos pos, String name, boolean v2) {}

	private void runSeed(ClientGameTestContext context, long seed) {
		context.runOnClient(mc -> mc.gui.setScreen(null));
		try (TestSingleplayerContext world = context.worldBuilder().setUseConsistentSettings(false).adjustSettings(state -> {
				((CasinoModeCreationState) state).burmaldaholic$setCasinoMode(true);
				state.setSeed(Long.toString(seed));
				state.setGameMode(WorldCreationUiState.SelectedGameMode.CREATIVE);
			}).create(); var q = ClientTestWorlds.quiet(context, world)) {
			context.waitTicks(20);
			context.runOnClient(mc -> mc.gui.setScreen(null));
			world.getServer().runCommand("gamemode spectator @p");
			world.getServer().runCommand("time set noon");
			List<BlockPos> searchFrom = List.of(new BlockPos(1500, 64, 1500), new BlockPos(-1500, 64, 1500));
			boolean v2 = world.getServer().computeOnServer(server -> !CasinoQa.standalone(server).isEmpty());
			for (int i = 0; i < (v2 ? searchFrom.size() : 1); i++) {
				BlockPos from = searchFrom.get(i);
				Optional<Found> found = world.getServer().computeOnServer(server -> locate(server, from, v2));
				if (found.isEmpty()) {
					failures.add("seed " + seed + ": no " + (v2 ? "casino" : "village") + " within 1600 blocks of " + from.toShortString());
					continue;
				}
				visit(context, world, seed, found.get());
			}
		}
	}

	/** Nearest casino (v0.2: {@code #burmaldaholic:casino}) or village (pre-merge, annex chance 1) to {@code from}. */
	private static Optional<Found> locate(MinecraftServer server, BlockPos from, boolean v2) {
		ServerLevel level = server.overworld();
		HolderSet<Structure> set;
		if (v2) {
			set = CasinoQa.casinoTag(server).map(h -> (HolderSet<Structure>) h).orElseThrow();
		} else {
			CasinoConfig.worldgen().villageCasino.chance = 1.0;
			set = server.registryAccess().lookupOrThrow(Registries.STRUCTURE)
				.get(TagKey.create(Registries.STRUCTURE, Identifier.parse("minecraft:village"))).map(h -> (HolderSet<Structure>) h).orElseThrow();
		}
		Pair<BlockPos, Holder<Structure>> p = level.getChunkSource().getGenerator().findNearestMapStructure(level, set, from, 100, false);
		if (p == null || p.getFirst().distManhattan(from) > 3200) {
			return Optional.empty();
		}
		String name = p.getSecond().unwrapKey().map(k -> k.identifier().getPath()).orElse("?");
		return Optional.of(new Found(p.getFirst(), name, v2));
	}

	private void visit(ClientGameTestContext context, TestSingleplayerContext world, long seed, Found f) {
		String tag = "seed " + seed + " " + f.name() + "@" + f.pos().toShortString();
		// generation cost: 9×9 chunks around the casino vs. casino-free control areas of the same world (GENPERF).
		// The worker pool must be idle first: the previous photo's teleport queues the player's whole view distance,
		// and whichever area was timed first used to pay for that backlog (17 s for a casino-free area, 15.8 s for a
		// riviera site). A control is timed before AND after the casino; the bar uses the cheaper one, so any backlog
		// left over lands on the first control and never makes the casino look better than it is.
		drain(context, world);
		double[] ms = world.getServer().computeOnServer(server -> {
			ServerLevel level = server.overworld();
			double before = generate(level, f.pos().offset(-1100, 0, -300));
			double casino = generate(level, f.pos());
			double after = generate(level, f.pos().offset(1100, 0, 300));
			return new double[] {casino, Math.min(before, after), before, after};
		});
		CasinoQa.log("terrain {}: 9x9 chunk generation {} ms vs control {} ms (before {} ms, after {} ms)", tag, Math.round(ms[0]),
			Math.round(ms[1]), Math.round(ms[2]), Math.round(ms[3]));
		if (f.v2() && ms[0] > COST_RATIO * ms[1] + COST_SLACK_MS) {
			failures.add(tag + ": generating around the casino costs " + Math.round(ms[0]) + " ms vs " + Math.round(ms[1]) + " ms (> "
				+ COST_RATIO + "x + " + COST_SLACK_MS + " ms)");
		}
		world.getServer().runCommand("tp @p " + f.pos().getX() + " 200 " + f.pos().getZ());
		try {
			world.getServer().waitFor(server -> loaded(server.overworld(), f.pos(), 4), CHUNK_WAIT);
		} catch (Throwable e) {
			failures.add(tag + ": chunks around did not load in " + CHUNK_WAIT + " ticks");
			return;
		}
		context.waitTicks(40); // markers hand their records over with server.execute
		Optional<Placed> placed = world.getServer().computeOnServer(server -> {
			ServerLevel level = server.overworld();
			Optional<CasinoRecord> r = CasinoQa.recordNear(level, f.pos(), 160);
			if (r.isEmpty()) {
				return Optional.empty();
			}
			var b = r.get().box();
			BoundingBox box = new BoundingBox(b.minX(), b.minY(), b.minZ(), b.maxX(), b.maxY(), b.maxZ());
			Target t = new Target(r.get().layoutId(), f.v2(), f.v2(), Optional.empty(), Optional.empty());
			return Optional.of(new Placed(t, box, CasinoQa.spots(level, box), r, -1));
		});
		if (placed.isEmpty()) {
			if (f.v2()) {
				failures.add(tag + ": no casino record after the chunks generated");
			} else {
				CasinoQa.log("terrain {}: this village has no casino annex (no free street end) — nothing to check", tag);
			}
			return;
		}
		Placed p = placed.get();
		String casinoId = p.record().map(CasinoRecord::id).orElse("");
		try { // O3: natural leaves are cleared once every chunk within one chunk of the casino is loaded
			world.getServer().waitFor(server -> dev.nezo.burmaldaholic.worldgen.CasinoFoliage.swept(casinoId), CHUNK_WAIT);
		} catch (Throwable e) {
			failures.add(tag + ": the foliage pass did not run in " + CHUNK_WAIT + " ticks");
		}
		List<String> problems = world.getServer().computeOnServer(server -> CasinoQa.terrainProblems(server.overworld(), p));
		CasinoQa.log("terrain {}: casino {} box {} with {} game blocks: {}", tag, p.target(), p.box(), p.spots().size(),
			problems.isEmpty() ? "ok" : problems);
		if (!problems.isEmpty()) {
			failures.add(tag + " (" + p.target() + "): " + String.join("; ", problems));
		}
		int floorY = p.spots().stream().mapToInt(s -> s.pos().getY()).min().orElse(p.box().minY() + 1);
		context.runOnClient(mc -> {
			if (!mc.gui.hud.isHidden()) {
				mc.gui.hud.toggle();
			}
		});
		try {
			CasinoClientQa.photograph(context, world, CasinoClientQa.vantagePoints(p, floorY).getFirst(),
				"jcasino_terrain_" + seed + "_" + p.target().name().replace('/', '_'));
		} finally {
			context.runOnClient(mc -> {
				if (mc.gui.hud.isHidden()) {
					mc.gui.hud.toggle();
				}
			});
		}
	}

	/** Wall time to bring the 9×9 chunks around {@code at} to FULL on the server thread. */
	private static double generate(ServerLevel level, BlockPos at) {
		long t0 = System.nanoTime();
		CasinoQa.loadChunks(level, at, 4);
		return (System.nanoTime() - t0) / 1e6;
	}

	/**
	 * Waits (bounded) until every chunk in the player's view distance is FULL, so no queued generation competes with the
	 * timed areas. Then a few quiet ticks for lighting and saving to settle.
	 */
	private static void drain(ClientGameTestContext context, TestSingleplayerContext world) {
		try {
			world.getServer().waitFor(server -> {
				var player = server.getPlayerList().getPlayers().getFirst();
				return loaded(server.overworld(), player.blockPosition(), server.getPlayerList().getViewDistance());
			}, CHUNK_WAIT);
		} catch (Throwable e) {
			CasinoQa.log("terrain: view-distance chunks still generating after {} ticks; timing anyway", CHUNK_WAIT);
		}
		// then until the chunk holder count stops changing (unloads/saves of the area the player left also queue work)
		int last = -1;
		for (int i = 0; i < 30; i++) {
			context.waitTicks(20);
			int now = world.getServer().computeOnServer(server -> server.overworld().getChunkSource().getLoadedChunksCount());
			if (now == last) {
				return;
			}
			last = now;
		}
		CasinoQa.log("terrain: chunk count still changing after 600 ticks; timing anyway");
	}

	private static boolean loaded(ServerLevel level, BlockPos at, int r) {
		int cx = at.getX() >> 4;
		int cz = at.getZ() >> 4;
		for (int x = cx - r; x <= cx + r; x++) {
			for (int z = cz - r; z <= cz + r; z++) {
				if (!level.hasChunk(x, z)) {
					return false;
				}
			}
		}
		return true;
	}
}
