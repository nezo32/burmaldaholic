package dev.nezo.burmaldaholic.worldgen;

import com.mojang.serialization.Codec;
import dev.nezo.burmaldaholic.Burmaldaholic;
import dev.nezo.burmaldaholic.core.table.CasinoTableBlock;
import net.fabricmc.fabric.api.attachment.v1.AttachmentRegistry;
import net.fabricmc.fabric.api.attachment.v1.AttachmentType;
import net.fabricmc.fabric.api.event.player.PlayerBlockBreakEvents;
import net.minecraft.commands.Commands;
import net.minecraft.core.BlockPos;
import net.minecraft.network.chat.Component;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.block.state.BlockState;
import org.jspecify.annotations.Nullable;

/**
 * House games (R-CB M9): the game blocks a generated casino placed are the house's, not loot.
 *
 * <p>A <b>house table</b> is a {@link CasinoTableBlock} (tables, slots, wheel, Plinko, cashiers) whose main block stands
 * inside the box of any complete {@link CasinoIndex} record of its dimension (standalone casinos, v0.2 and v0.1 annexes,
 * Piglin Parlors, High Roller Lounges) and that no player placed. A table a player places carries the persistent
 * block-entity attachment {@code burmaldaholic:player_placed_table} ({@link #markPlayerPlaced}) and stays an ordinary
 * table everywhere. Always on (no config key), independent of casino mode.
 *
 * <p>What this class enforces itself ({@code PlayerBlockBreakEvents.BEFORE}, alongside {@code Ownership.beforeBreak};
 * either may cancel):
 * <ul>
 *   <li>players without operator permission (level 2, any game mode) cannot break a house table: cancelled with
 *       {@link #PROTECTED_KEY};</li>
 *   <li>an operator in Survival removes it without an item: the hook removes the main block itself with
 *       {@code destroyBlock(main, false, player)} and cancels vanilla's break (a creative break drops nothing anyway).</li>
 * </ul>
 *
 * <p><b>Contract with the multi-block table package (MT, owner of {@code CasinoTableBlock} / {@code TableParts})</b> — the
 * block calls these static decisions with the MAIN block position:
 * <ul>
 *   <li>{@link #dropsAllowed} in {@code TableParts.removeAll}'s drop decision (every removal path: ops, {@code /setblock
 *       … destroy}, withers): false → no item;</li>
 *   <li>{@link #explosionProof} in {@code onExplosionHit} (or the explosion position filter): true → the table stays;</li>
 *   <li>{@link #markPlayerPlaced} from {@code setPlacedBy} on the main block's entity when the placer is a player.</li>
 * </ul>
 * Pistons never move tables (block entities; MT adds {@code pushReaction(BLOCK)}). Lookups only scan the casino index:
 * no chunk is loaded.
 */
public final class HouseGames {
	public static final String PROTECTED_KEY = "msg.burmaldaholic.worldgen.house_table_protected";
	private static @Nullable AttachmentType<Boolean> playerPlaced;

	private HouseGames() {}

	public static void register() {
		playerPlaced = AttachmentRegistry.createPersistent(Burmaldaholic.id("player_placed_table"), Codec.BOOL);
		PlayerBlockBreakEvents.BEFORE.register(HouseGames::beforeBreak);
	}

	// ---- decisions (MT contract) ----------------------------------------------------------------------------------------

	/** True for the table whose main block is {@code mainPos}: generated by a casino, not placed by a player. */
	public static boolean isHouseTable(ServerLevel level, BlockPos mainPos, @Nullable BlockEntity mainBe) {
		if (isPlayerPlaced(mainBe)) {
			return false;
		}
		CasinoIndex index = CasinoIndex.get(level.getServer());
		return !index.casinos().isEmpty() && index.recordAt(level.dimension().identifier().toString(), mainPos) != null;
	}

	/** May removing this table drop its item? False for house tables, whoever removes them ({@code player} may be null). */
	public static boolean dropsAllowed(ServerLevel level, BlockPos mainPos, @Nullable BlockEntity mainBe, @Nullable Player player) {
		return !isHouseTable(level, mainPos, mainBe);
	}

	/** May this player break the table? Operators may; others not a house table. */
	public static boolean breakAllowed(ServerLevel level, BlockPos mainPos, @Nullable BlockEntity mainBe, Player player) {
		return player instanceof ServerPlayer sp && isOperator(sp) || !isHouseTable(level, mainPos, mainBe);
	}

	/** Do explosions (TNT, creepers, fireballs) leave this table standing? True for house tables. */
	public static boolean explosionProof(ServerLevel level, BlockPos mainPos, @Nullable BlockEntity mainBe) {
		return isHouseTable(level, mainPos, mainBe);
	}

	/** A player placed this table: it is theirs even inside a generated casino. Call with the main block's entity. */
	public static void markPlayerPlaced(@Nullable BlockEntity mainBe) {
		if (mainBe != null && playerPlaced != null) {
			mainBe.setAttached(playerPlaced, true);
			mainBe.setChanged();
		}
	}

	public static boolean isPlayerPlaced(@Nullable BlockEntity be) {
		return be != null && playerPlaced != null && Boolean.TRUE.equals(be.getAttached(playerPlaced));
	}

	static boolean isOperator(ServerPlayer player) {
		return Commands.LEVEL_GAMEMASTERS.check(player.permissions());
	}

	// ---- break event ----------------------------------------------------------------------------------------------------

	/**
	 * The main block of the table at {@code pos}. Single-block tables: the block itself. When MT-1 lands (3×2 tables)
	 * this resolves a part to its main block with {@code TableParts.mainOf} (MT-DESIGN §4).
	 */
	static BlockPos mainOf(ServerLevel level, BlockPos pos, BlockState state) {
		return pos;
	}

	/** PlayerBlockBreakEvents.BEFORE: non-operators may not break a house table; operators remove it without an item. */
	static boolean beforeBreak(Level level, Player player, BlockPos pos, BlockState state, @Nullable BlockEntity be) {
		if (!(state.getBlock() instanceof CasinoTableBlock) || !(level instanceof ServerLevel serverLevel) || !(player instanceof ServerPlayer sp)) {
			return true;
		}
		BlockPos main = mainOf(serverLevel, pos, state);
		BlockEntity mainBe = main.equals(pos) ? be : level.getBlockEntity(main);
		if (!isHouseTable(serverLevel, main, mainBe)) {
			return true;
		}
		if (!isOperator(sp)) {
			sp.sendOverlayMessage(Component.translatable(PROTECTED_KEY));
			return false;
		}
		if (sp.isCreative()) {
			return true; // creative breaks drop nothing
		}
		level.destroyBlock(main, false, player);
		return false;
	}
}
