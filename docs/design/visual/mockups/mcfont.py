def glyph(ch):
    return G.get(ch, G['?'])


def width(text, bold=False, scale=1):
    w = 0
    for ch in text:
        w += len(glyph(ch)[0]) + 1 + (1 if bold else 0)
    return max(0, w - 1) * scale


def draw(img, x, y, text, color, shadow=True, bold=False, scale=1, outline=None):
    """Draws `text` at GUI pixel (x, y) on an RGBA image; returns the advance width."""
    px = img.load()
    W, H = img.size

    def put(xx, yy, col):
        for j in range(scale):
            for i in range(scale):
                X, Y = xx + i, yy + j
                if 0 <= X < W and 0 <= Y < H:
                    px[X, Y] = col

    def run(ox, oy, col):
        cx = ox
        for ch in text:
            g = glyph(ch)
            for r, row in enumerate(g):
                for c, v in enumerate(row):
                    if v == '#':
                        for b in range(2 if bold else 1):
                            put(cx + (c + b) * scale, oy + r * scale, col)
            cx += (len(g[0]) + 1 + (1 if bold else 0)) * scale
        return cx - ox

    col = tuple(color) + ((255,) if len(color) == 3 else ())
    if outline is not None:
        oc = tuple(outline) + ((255,) if len(outline) == 3 else ())
        for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1)):
            run(x + dx * scale, y + dy * scale, oc)
    elif shadow:
        sc = (col[0] // 4, col[1] // 4, col[2] // 4, 255)
        run(x + scale, y + scale, sc)
    return run(x, y, col)


def center(img, cx, y, text, color, **kw):
    w = width(text, kw.get('bold', False), kw.get('scale', 1))
    draw(img, cx - w // 2, y, text, color, **kw)
    return w


def right(img, rx, y, text, color, **kw):
    w = width(text, kw.get('bold', False), kw.get('scale', 1))
    draw(img, rx - w, y, text, color, **kw)
    return w

