/** Validates every grid (16 × 16, legend complete). */
export function validateArt(list) {
  for (const s of list) {
    if (s.grid.length !== 16) throw new Error(`${s.id}: ${s.grid.length} rows`);
    s.grid.forEach((row, i) => {
      if (row.length !== 16) throw new Error(`${s.id}: row ${i} has ${row.length} px`);
      for (const ch of row) if (ch !== '.' && !s.pal[ch]) throw new Error(`${s.id}: no colour for '${ch}'`);
    });
  }
}
